-- Wire bindTextId specials into compiled map talk scripts (oneshot gift/battle).
function ModWriter.applySpecialEncounterBinds(project, scripts)
  local specs = project.specialEncounters
  if type(specs) ~= "table" or not next(specs) then return end
  local State = require("State")
  local cmd = (project.id or "content_mod") .. ":give_special"
  local ids = {}
  for sid in pairs(specs) do ids[#ids + 1] = sid end
  table.sort(ids)
  for _, sid in ipairs(ids) do
    local spec = specs[sid]
    local mapId = type(spec) == "table" and spec.mapId
    local textId = type(spec) == "table" and spec.bindTextId
    if type(spec) == "table"
        and type(mapId) == "string" and mapId ~= ""
        and type(textId) == "string" and textId ~= "" then
      local unique = spec.unique ~= false
      local done = State.modFlag(project, (spec.flag and spec.flag ~= "" and spec.flag)
        or ((spec.kind == "battle") and ("BEAT_" .. sid) or ("GOT_" .. sid)))

      -- Battle + Bind text on a map object: headers/trainerClass already
      -- wired by ensureTrainerHeaders.  A talk script would suppress sight
      -- (checkTrainerSight skips NPCs with talkScript) and is unnecessary
      -- because engageTrainer runs on interact.
      local wiredBattle = false
      if (spec.kind or "gift") == "battle" then
        local map = project.maps and project.maps[mapId]
        local wantClass = specialTrainerId(sid)
        if type(map) == "table" then
          for _, obj in ipairs(map.objects or {}) do
            if type(obj) == "table" and obj.text == textId
                and obj.trainerClass == wantClass then
              wiredBattle = true
              break
            end
          end
        end
      end
      if wiredBattle then
        if scripts[mapId] and scripts[mapId].talk then
          scripts[mapId].talk[textId] = nil
        end
      else
        local rows = {}
        if (spec.kind or "gift") == "battle" then
          local cls = specialTrainerId(sid)
          local before = spec.text or "Let's fight!"
          local won = spec.won or "I lost..."
          local after = spec.after or "You're strong."
          rows[#rows + 1] = { "face_player" }
          if unique then
            rows[#rows + 1] = { "check_flag", done }
            rows[#rows + 1] = { "jump_if_true", "after_fight" }
          end
          rows[#rows + 1] = { "show_text", before }
          rows[#rows + 1] = { "start_battle", "trainer", cls, 1 }
          rows[#rows + 1] = { "jump_if_false", "end" }
          rows[#rows + 1] = { "show_text", won }
          if unique then
            rows[#rows + 1] = { "set_flag", done }
          end
          rows[#rows + 1] = { "jump", "end" }
          if unique then
            rows[#rows + 1] = { "label", "after_fight" }
            rows[#rows + 1] = { "show_text", after }
          end
        else
          local intro = spec.text or "Here! Take this POKeMON!"
          local after = spec.after or "I already gave you one."
          if unique then
            rows[#rows + 1] = { "check_flag", done }
            rows[#rows + 1] = { "jump_if_true", "after_mon" }
          end
          rows[#rows + 1] = { "show_text", intro }
          rows[#rows + 1] = { cmd, sid }
          if unique then
            rows[#rows + 1] = { "set_flag", done }
            rows[#rows + 1] = { "jump", "end" }
            rows[#rows + 1] = { "label", "after_mon" }
            rows[#rows + 1] = { "show_text", after }
          end
        end
        rows[#rows + 1] = { "label", "end" }
        rows = ModWriter.relabelNumericJumps(rows)
        scripts[mapId] = scripts[mapId] or { talk = {} }
        scripts[mapId].talk[textId] = rows
      end
    end
  end
end

-- Convert editor step lists into ScriptRunner command rows.
function ModWriter.compileTalkScripts(project)
  local byMap = {}
  for key, script in pairs(project.talkScripts or {}) do
    local mapId = script.mapId or key:match("^([^/]+)/")
    local textId = script.textId or key:match("/(.+)$")
    if mapId and textId and type(script.steps) == "table" then
      local rows = ModWriter.stepsToRows(project, script.steps)
      if #rows > 0 then
        byMap[mapId] = byMap[mapId] or { talk = {} }
        byMap[mapId].talk[textId] = rows
      end
    end
  end
  return byMap
end

function ModWriter.stepsToRows(project, steps)
  local rows = {}
  local function flagName(short)
    local State = require("State")
    return State.modFlag(project, short)
  end

  for _, step in ipairs(steps) do
    local kind = step.kind or "show_text"
    if kind == "raw" then
      local row = step.row
      if type(step.note) == "string" and step.note:match("%S") then
        row = ModWriter.parseEngineLine(step.note)
      end
      if type(row) == "table" and row[1] then
        local copy = {}
        for i, v in ipairs(row) do copy[i] = v end
        rows[#rows + 1] = copy
      end
    elseif kind == "show_image" then
      local path = step.path or step.image or ""
      if path ~= "" then
        if step.text and step.text ~= "" then
          rows[#rows + 1] = { "show_image", path, step.text }
        else
          rows[#rows + 1] = { "show_image", path }
        end
      end
    elseif kind == "show_text" or kind == "show_label" then
      local t = step.text or step.label or ""
      if t ~= "" then rows[#rows + 1] = { "show_text", t } end
    elseif kind == "ask" then
      local t = step.text or "OK?"
      rows[#rows + 1] = { "ask", t }
      if step.skipOnNo ~= false then
        rows[#rows + 1] = { "jump_if_false", "end" }
      end
    elseif kind == "label" then
      local name = step.name or step.label or "label"
      if name ~= "" then rows[#rows + 1] = { "label", name } end
    elseif kind == "jump" then
      local name = step.name or step.label or "end"
      rows[#rows + 1] = { "jump", name }
    elseif kind == "jump_if_yes" then
      local name = step.name or step.label or "end"
      rows[#rows + 1] = { "jump_if_true", name }
    elseif kind == "jump_if_no" then
      local name = step.name or step.label or "end"
      rows[#rows + 1] = { "jump_if_false", name }
    elseif kind == "face_player" then
      rows[#rows + 1] = { "face_player" }
    elseif kind == "heal_party" then
      rows[#rows + 1] = { "heal_party" }
    elseif kind == "set_flag" then
      rows[#rows + 1] = { "set_flag", flagName(step.flag or "FLAG") }
    elseif kind == "clear_flag" then
      rows[#rows + 1] = { "clear_flag", flagName(step.flag or "FLAG") }
    elseif kind == "check_flag_skip" then
      rows[#rows + 1] = { "check_flag", flagName(step.flag or "FLAG") }
      rows[#rows + 1] = { "jump_if_true", "end" }
    elseif kind == "check_flag_missing" then
      rows[#rows + 1] = { "check_flag", flagName(step.flag or "FLAG") }
      rows[#rows + 1] = { "jump_if_false", "end" }
    elseif kind == "give_item" then
      rows[#rows + 1] = {
        "give_item", step.item or "POTION", tonumber(step.count) or 1,
      }
    elseif kind == "take_item" then
      rows[#rows + 1] = {
        "take_item", step.item or "POTION", tonumber(step.count) or 1,
      }
    elseif kind == "check_item_skip" then
      rows[#rows + 1] = { "check_item", step.item or "POTION" }
      rows[#rows + 1] = { "jump_if_true", "end" }
    elseif kind == "check_item_missing" then
      rows[#rows + 1] = { "check_item", step.item or "POTION" }
      rows[#rows + 1] = { "jump_if_false", "end" }
    elseif kind == "give_pokemon" then
      local sp = step.species or "PIKACHU"
      local lv = tonumber(step.level) or 5
      if step.skipNickname then
        rows[#rows + 1] = { "give_pokemon", sp, lv, true }
      else
        rows[#rows + 1] = { "give_pokemon", sp, lv }
      end
    elseif kind == "give_starter" then
      -- Gift + vanilla starter flag (and optional rival index 1/2/3).
      local sp = step.species or "BULBASAUR"
      local lv = tonumber(step.level) or 5
      if step.text and step.text ~= "" then
        rows[#rows + 1] = { "show_text", step.text }
      end
      if step.skipNickname then
        rows[#rows + 1] = { "give_pokemon", sp, lv, true }
      else
        rows[#rows + 1] = { "give_pokemon", sp, lv }
      end
      rows[#rows + 1] = { "set_flag", "EVENT_GOT_STARTER" }
      if step.choseFlag and step.choseFlag ~= "" then
        rows[#rows + 1] = { "set_flag", flagName(step.choseFlag) }
      end
      local rival = tonumber(step.rivalStarter)
      if rival and rival >= 1 and rival <= 3 then
        rows[#rows + 1] = { "set_field", "rivalStarter", rival }
      end
    elseif kind == "give_money" then
      rows[#rows + 1] = { "give_money", tonumber(step.amount) or 500 }
    elseif kind == "warp" then
      rows[#rows + 1] = {
        "warp",
        step.map or "PALLET_TOWN",
        tonumber(step.x) or 0,
        tonumber(step.y) or 0,
        step.facing or "down",
      }
    elseif kind == "wild_battle" then
      rows[#rows + 1] = {
        "start_battle", "wild",
        step.species or "PIDGEY", tonumber(step.level) or 5,
      }
    elseif kind == "trainer_battle" then
      if step.text and step.text ~= "" then
        rows[#rows + 1] = { "show_text", step.text }
      end
      rows[#rows + 1] = {
        "start_battle", "trainer",
        step.trainer or "OPP_BUG_CATCHER", tonumber(step.party) or 1,
      }
      if step.won and step.won ~= "" then
        rows[#rows + 1] = { "jump_if_false", "end" }
        rows[#rows + 1] = { "show_text", step.won }
      end
    elseif kind == "oneshot_trainer" then
      local done = flagName(step.flag or "BEAT_TRAINER")
      local before = step.text or "Let's fight!"
      local won = step.won or "I lost..."
      local after = step.after or "You're strong."
      local cls = step.trainer or "OPP_BUG_CATCHER"
      local party = tonumber(step.party) or 1
      rows[#rows + 1] = { "face_player" }
      rows[#rows + 1] = { "check_flag", done }
      rows[#rows + 1] = { "jump_if_true", "after_fight" }
      rows[#rows + 1] = { "show_text", before }
      rows[#rows + 1] = { "start_battle", "trainer", cls, party }
      rows[#rows + 1] = { "jump_if_false", "end" }
      rows[#rows + 1] = { "show_text", won }
      rows[#rows + 1] = { "set_flag", done }
      rows[#rows + 1] = { "jump", "end" }
      rows[#rows + 1] = { "label", "after_fight" }
      rows[#rows + 1] = { "show_text", after }
    elseif kind == "set_field" then
      local key = step.field or "mod:value"
      local val = step.value
      if step.valueType == "number" then
        val = tonumber(val) or 0
      elseif step.valueType == "bool" then
        val = (tostring(val) == "true" or val == true)
      end
      rows[#rows + 1] = { "set_field", key, val }
    elseif kind == "oneshot_gift" then
      local done = flagName(step.flag or "DONE")
      local intro = step.text or "Here you go!"
      local after = step.after or "I already gave you one."
      local item = step.item or "POTION"
      rows[#rows + 1] = { "check_flag", done }
      rows[#rows + 1] = { "jump_if_true", "after" }
      rows[#rows + 1] = { "show_text", intro }
      rows[#rows + 1] = { "give_item", item, tonumber(step.count) or 1 }
      rows[#rows + 1] = { "set_flag", done }
      rows[#rows + 1] = { "jump", "end" }
      rows[#rows + 1] = { "label", "after" }
      rows[#rows + 1] = { "show_text", after }
    elseif kind == "oneshot_pokemon" then
      local done = flagName(step.flag or "GOT_MON")
      local intro = step.text or "Here! Take this POKeMON!"
      local after = step.after or "I already gave you one."
      local sp = step.species or "EEVEE"
      local lv = tonumber(step.level) or 25
      rows[#rows + 1] = { "check_flag", done }
      rows[#rows + 1] = { "jump_if_true", "after_mon" }
      rows[#rows + 1] = { "show_text", intro }
      if step.skipNickname then
        rows[#rows + 1] = { "give_pokemon", sp, lv, true }
      else
        rows[#rows + 1] = { "give_pokemon", sp, lv }
      end
      rows[#rows + 1] = { "set_flag", done }
      rows[#rows + 1] = { "jump", "end" }
      rows[#rows + 1] = { "label", "after_mon" }
      rows[#rows + 1] = { "show_text", after }
    end
  end
  -- Avoid duplicating a trailing end label already present from decompile.
  local last = rows[#rows]
  if not (last and last[1] == "label" and last[2] == "end") then
    rows[#rows + 1] = { "label", "end" }
  end
  -- Vanilla ports use numeric jump targets (row indices).  Cloning through
  -- the editor stringifies them ("22"), which fails validation — rewrite
  -- digit targets into real labels before emit.
  return ModWriter.relabelNumericJumps(rows)
end

-- Turn numeric / digit-string jump targets into { "label", "_row_N" } anchors
-- so ScriptRunner.validate accepts editor-emitted talk scripts.
function ModWriter.relabelNumericJumps(rows)
  if type(rows) ~= "table" then return rows end
  local function jumpNum(t)
    if type(t) == "number" and t % 1 == 0 then return t end
    if type(t) == "string" and t:match("^%d+$") then return tonumber(t) end
    return nil
  end
  local src = {}
  for i, row in ipairs(rows) do
    if type(row) == "table" then
      local c = {}
      for j = 1, #row do c[j] = row[j] end
      src[i] = c
    else
      src[i] = row
    end
  end
  local targets = {}
  for _, row in ipairs(src) do
    if type(row) == "table" then
      local v = row[1]
      if v == "jump" or v == "jump_if_true" or v == "jump_if_false" then
        local n = jumpNum(row[2])
        if n and n >= 1 and n <= #src then targets[n] = true end
      end
    end
  end
  if not next(targets) then return src end
  local function labelName(n) return ("_row_%d"):format(n) end
  local out = {}
  for i, row in ipairs(src) do
    if targets[i] then
      out[#out + 1] = { "label", labelName(i) }
    end
    out[#out + 1] = row
  end
  for _, row in ipairs(out) do
    if type(row) == "table" then
      local v = row[1]
      if v == "jump" or v == "jump_if_true" or v == "jump_if_false" then
        local n = jumpNum(row[2])
        if n and targets[n] then row[2] = labelName(n) end
      end
    end
  end
  return out
end

-- Tokenize an "Engine cmd" line into a ScriptRunner row.
-- Supports words, numbers, booleans, "quoted strings", and {table} literals.
function ModWriter.parseEngineLine(line)
  line = tostring(line or ""):gsub("^%s+", ""):gsub("%s+$", "")
  if line == "" then return { "wait", 0 } end
  local parts = {}
  local i, n = 1, #line
  while i <= n do
    local c = line:sub(i, i)
    if c:match("%s") then
      i = i + 1
    elseif c == '"' or c == "'" then
      local q, j, buf = c, i + 1, {}
      while j <= n do
        local ch = line:sub(j, j)
        if ch == "\\" and j < n then
          buf[#buf + 1] = line:sub(j + 1, j + 1)
          j = j + 2
        elseif ch == q then
          j = j + 1
          break
        else
          buf[#buf + 1] = ch
          j = j + 1
        end
      end
      parts[#parts + 1] = table.concat(buf)
      i = j
    elseif c == "{" then
      local depth, j = 1, i + 1
      while j <= n and depth > 0 do
        local ch = line:sub(j, j)
        if ch == "{" then depth = depth + 1
        elseif ch == "}" then depth = depth - 1 end
        j = j + 1
      end
      local chunk = line:sub(i, j - 1)
      local ok, val = pcall(function()
        return assert(load("return " .. chunk, "=engine_cmd"))()
      end)
      parts[#parts + 1] = ok and val or chunk
      i = j
    else
      local j = i
      while j <= n and not line:sub(j, j):match("%s") do j = j + 1 end
      local tok = line:sub(i, j - 1)
      if tok == "true" then parts[#parts + 1] = true
      elseif tok == "false" then parts[#parts + 1] = false
      elseif tonumber(tok) then parts[#parts + 1] = tonumber(tok)
      else parts[#parts + 1] = tok end
      i = j
    end
  end
  if #parts == 0 then return { "wait", 0 } end
  return parts
end

local function formatEngineValue(v, depth, bareOk)
  depth = (depth or 0) + 1
  if depth > 4 then return "{...}" end
  local tv = type(v)
  if tv == "string" then
    -- Bare identifiers only for top-level script args (verb, FLAG, SPECIES).
    -- Inside {tables} always quote so load() round-trips.
    if bareOk and v:match("^[%w_]+$") then return v end
    return string.format("%q", v)
  elseif tv == "number" or tv == "boolean" then
    return tostring(v)
  elseif tv == "table" then
    local bits, n = {}, #v
    for i = 1, n do bits[#bits + 1] = formatEngineValue(v[i], depth, false) end
    local keys = {}
    for k in pairs(v) do
      if not (type(k) == "number" and k >= 1 and k <= n and k % 1 == 0) then
        keys[#keys + 1] = k
      end
    end
    table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
    for _, k in ipairs(keys) do
      local key = (type(k) == "string" and k:match("^[%a_][%w_]*$"))
        and k or ("[" .. formatEngineValue(k, depth, false) .. "]")
      bits[#bits + 1] = key .. " = " .. formatEngineValue(v[k], depth, false)
    end
    return "{ " .. table.concat(bits, ", ") .. " }"
  end
  return "nil"
end

function ModWriter.formatEngineLine(row)
  if type(row) ~= "table" then return tostring(row or "") end
  local parts = {}
  for i = 1, #row do
    parts[i] = formatEngineValue(row[i], 0, true)
  end
  return table.concat(parts, " ")
end

-- Inverse of stepsToRows for browsing vanilla / mod ScriptRunner rows.
-- Recognizes common editor pairings; unknown verbs become raw steps.
function ModWriter.rowsToSteps(rows)
  local steps = {}
  if type(rows) ~= "table" then return steps end
  rows = ModWriter.relabelNumericJumps(rows)

  local function shortFlag(name)
    name = tostring(name or "")
    return name:gsub("^MOD_[^_]+_", "")
  end

  local function pushRaw(row)
    local copy = {}
    for i = 1, #row do copy[i] = row[i] end
    steps[#steps + 1] = {
      kind = "raw",
      note = ModWriter.formatEngineLine(copy),
      row = copy,
    }
  end

  local i = 1
  while i <= #rows do
    local row = rows[i]
    if type(row) == "function" then
      steps[#steps + 1] = { kind = "raw", note = "(inline Lua)" }
      i = i + 1
    elseif type(row) ~= "table" or row[1] == nil then
      i = i + 1
    else
      local verb = row[1]
      local n1 = rows[i + 1]
      local paired = type(n1) == "table" and n1[1]

      if verb == "show_image" then
        steps[#steps + 1] = {
          kind = "show_image",
          path = tostring(row[2] or ""),
          text = (type(row[3]) == "string" and row[3]) or "",
        }
        i = i + 1
      elseif verb == "show_text" then
        steps[#steps + 1] = { kind = "show_text", text = tostring(row[2] or "") }
        i = i + 1
      elseif verb == "ask" then
        local step = { kind = "ask", text = tostring(row[2] or "OK?"), skipOnNo = false }
        if paired == "jump_if_false" and (n1[2] == "end" or n1[2] == nil) then
          step.skipOnNo = true
          i = i + 2
        else
          i = i + 1
        end
        steps[#steps + 1] = step
      elseif verb == "label" then
        -- Skip synthetic trailing end unless it's mid-script.
        if row[2] == "end" and i == #rows then
          i = i + 1
        else
          steps[#steps + 1] = { kind = "label", name = tostring(row[2] or "label") }
          i = i + 1
        end
      elseif verb == "jump" then
        steps[#steps + 1] = { kind = "jump", name = tostring(row[2] or "end") }
        i = i + 1
      elseif verb == "jump_if_true" then
        steps[#steps + 1] = { kind = "jump_if_yes", name = tostring(row[2] or "end") }
        i = i + 1
      elseif verb == "jump_if_false" then
        steps[#steps + 1] = { kind = "jump_if_no", name = tostring(row[2] or "end") }
        i = i + 1
      elseif verb == "face_player" then
        steps[#steps + 1] = { kind = "face_player" }
        i = i + 1
      elseif verb == "heal_party" then
        steps[#steps + 1] = { kind = "heal_party" }
        i = i + 1
      elseif verb == "set_flag" then
        steps[#steps + 1] = { kind = "set_flag", flag = shortFlag(row[2]) }
        i = i + 1
      elseif verb == "clear_flag" then
        steps[#steps + 1] = { kind = "clear_flag", flag = shortFlag(row[2]) }
        i = i + 1
      elseif verb == "check_flag" and paired == "jump_if_true" and n1[2] == "end" then
        steps[#steps + 1] = { kind = "check_flag_skip", flag = shortFlag(row[2]) }
        i = i + 2
      elseif verb == "check_flag" and paired == "jump_if_false" and n1[2] == "end" then
        steps[#steps + 1] = { kind = "check_flag_missing", flag = shortFlag(row[2]) }
        i = i + 2
      elseif verb == "check_item" and paired == "jump_if_true" and n1[2] == "end" then
        steps[#steps + 1] = { kind = "check_item_skip", item = tostring(row[2] or "POTION") }
        i = i + 2
      elseif verb == "check_item" and paired == "jump_if_false" and n1[2] == "end" then
        steps[#steps + 1] = {
          kind = "check_item_missing", item = tostring(row[2] or "POTION"),
        }
        i = i + 2
      elseif verb == "give_item" then
        steps[#steps + 1] = {
          kind = "give_item",
          item = tostring(row[2] or "POTION"),
          count = tonumber(row[3]) or 1,
        }
        i = i + 1
      elseif verb == "take_item" then
        steps[#steps + 1] = {
          kind = "take_item",
          item = tostring(row[2] or "POTION"),
          count = tonumber(row[3]) or 1,
        }
        i = i + 1
      elseif verb == "give_pokemon" then
        steps[#steps + 1] = {
          kind = "give_pokemon",
          species = tostring(row[2] or "PIKACHU"),
          level = tonumber(row[3]) or 5,
          skipNickname = row[4] and true or nil,
        }
        i = i + 1
      elseif verb == "give_money" then
        steps[#steps + 1] = { kind = "give_money", amount = tonumber(row[2]) or 500 }
        i = i + 1
      elseif verb == "warp" then
        steps[#steps + 1] = {
          kind = "warp",
          map = tostring(row[2] or "PALLET_TOWN"),
          x = tonumber(row[3]) or 0,
          y = tonumber(row[4]) or 0,
          facing = tostring(row[5] or "down"),
        }
        i = i + 1
      elseif verb == "start_battle" and row[2] == "wild" then
        steps[#steps + 1] = {
          kind = "wild_battle",
          species = tostring(row[3] or "PIDGEY"),
          level = tonumber(row[4]) or 5,
        }
        i = i + 1
      elseif verb == "start_battle" and row[2] == "trainer" then
        steps[#steps + 1] = {
          kind = "trainer_battle",
          trainer = tostring(row[3] or "OPP_BUG_CATCHER"),
          party = tonumber(row[4]) or 1,
        }
        i = i + 1
      elseif verb == "set_field" then
        local val = row[3]
        local vt = "str"
        if type(val) == "number" then vt = "number"
        elseif type(val) == "boolean" then vt = "bool" end
        steps[#steps + 1] = {
          kind = "set_field",
          field = tostring(row[2] or "mod:value"),
          value = tostring(val == nil and "" or val),
          valueType = vt,
        }
        i = i + 1
      else
        pushRaw(row)
        i = i + 1
      end
    end
  end
  return steps
end

return ModWriter
